#!/usr/bin/env bash
# Generate src/godot/theme_overrides.zig: the theme override properties each
# Control and Window class offers, inherited items included.
#
#   GODOT=/path/to/godot tools/gen_theme_overrides.sh > src/godot/theme_overrides.zig
#   zig fmt src/godot/theme_overrides.zig
#
# Control::_set takes an override of any name, but _get_property_list lists
# only the class's own theme items, so a misspelled one is drawn with by
# nothing and dropped by the editor's next save. The list comes from the
# engine, as the property order does, since the class reference differs in
# a few places. Only classes the class table carries are kept.
set -euo pipefail

GODOT="${GODOT:-godot}"
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

printf 'config_version=5\n\n[application]\n\nconfig/name="godot-cli theme overrides"\n' > "$work/project.godot"
cp "$repo_root/tools/theme_overrides/dump.gd" "$work/dump.gd"
"$GODOT" --headless --editor --path "$work" --script res://dump.gd > "$work/godot.log" 2>&1 || true
[ -f "$work/theme_overrides.json" ] || { echo "the editor wrote no theme_overrides.json:" >&2; cat "$work/godot.log" >&2; exit 1; }

python3 - "$work/theme_overrides.json" "$repo_root/src/godot/class_table.zig" <<'PY'
import json, re, sys
data = json.load(open(sys.argv[1]))
known = set(re.findall(r'\.name = "([A-Za-z0-9_]+)",\n\s*\.inherits', open(sys.argv[2]).read()))
def zs(t): return '"' + t.replace("\\", "\\\\").replace('"', '\\"') + '"'
out = sys.stdout
out.write("//! The theme override properties each Control and Window class offers,\n")
out.write("//! inherited items included, sorted: the names a save keeps.\n//!\n")
out.write("//! GENERATED by tools/gen_theme_overrides.sh from the editor binary.\n")
out.write("//! " + data["version"] + ". Do not edit; regenerate instead.\n\n")
out.write("pub const Entry = struct { class: []const u8, overrides: []const []const u8 };\n\n")
out.write('pub const godot_version = ' + zs(data["version"]) + ';\n\n')
out.write("pub const classes = [_]Entry{\n")
for cls in sorted(data["classes"]):
    if cls not in known: continue
    names = sorted(data["classes"][cls])
    out.write("    .{ .class = " + zs(cls) + ", .overrides = &.{" + ", ".join(zs(n) for n in names) + "} },\n")
out.write("};\n")
PY
