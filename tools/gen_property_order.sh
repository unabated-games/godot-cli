#!/usr/bin/env bash
# Generate src/godot/property_order.zig: every class's own stored properties,
# in the order the class registers them.
#
#   GODOT=/path/to/godot tools/gen_property_order.sh > src/godot/property_order.zig
#   zig fmt src/godot/property_order.zig
#
# A save writes a node's properties in get_property_list order: base class
# first, each class's registered properties in registration order. The class
# reference lists them alphabetically, so the order comes from the engine
# itself, as the export option tables do. Only classes the class table
# carries are kept.
set -euo pipefail

GODOT="${GODOT:-godot}"
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

printf 'config_version=5\n\n[application]\n\nconfig/name="godot-cli property order"\n' > "$work/project.godot"
cp "$repo_root/tools/property_order/dump.gd" "$work/dump.gd"
"$GODOT" --headless --editor --path "$work" --script res://dump.gd > "$work/godot.log" 2>&1 || true
[ -f "$work/property_order.json" ] || { echo "the editor wrote no property_order.json:" >&2; cat "$work/godot.log" >&2; exit 1; }

python3 - "$work/property_order.json" "$repo_root/src/godot/class_table.zig" <<'PY'
import json, re, sys
data = json.load(open(sys.argv[1]))
known = set(re.findall(r'\.name = "([A-Za-z0-9_]+)",\n\s*\.inherits', open(sys.argv[2]).read()))
def zs(t): return '"' + t.replace("\\", "\\\\").replace('"', '\\"') + '"'
out = sys.stdout
out.write("//! Each class's own stored properties, in the order the class registers\n")
out.write("//! them: the order a save writes them in, base class first.\n//!\n")
out.write("//! GENERATED by tools/gen_property_order.sh from the editor binary.\n")
out.write("//! " + data["version"] + ". Do not edit; regenerate instead.\n\n")
out.write("pub const Entry = struct { class: []const u8, properties: []const []const u8 };\n\n")
out.write('pub const godot_version = ' + zs(data["version"]) + ';\n\n')
out.write("pub const classes = [_]Entry{\n")
for cls in sorted(data["classes"]):
    if cls not in known: continue
    props = data["classes"][cls]
    out.write("    .{ .class = " + zs(cls) + ", .properties = &.{" + ", ".join(zs(p) for p in props) + "} },\n")
out.write("};\n")
PY
